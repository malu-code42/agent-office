ACCENTS = {'acute': ["..#.", ".#.."], 'circ': [".##.", "#..#"], 'tilde': [".#.#", "#.#."]}
COMPOSE = {'á': ('a', 'acute'), 'é': ('e', 'acute'), 'í': ('i', 'acute'), 'ó': ('o', 'acute'), 'ú': ('u', 'acute'),
           'â': ('a', 'circ'), 'ê': ('e', 'circ'), 'ô': ('o', 'circ'), 'ã': ('a', 'tilde'), 'õ': ('o', 'tilde')}


def _rows(s, h=9):
    r = s.split('|')
    return r + ['.' * len(r[0])] * (h - len(r))


def glyph(ch):
    if ch == ' ':
        return ['..'] * 9
    if ch in ('.', ','):
        return ['.'] * 6 + ['#', '#' if ch == ',' else '.', '.']
    if ch == '·':
        return ['.'] * 3 + ['#'] + ['.'] * 5
    if ch == ':':
        return ['.', '.', '#', '.', '.', '#', '.', '.', '.']
    if ch == '-':
        return ['...'] * 3 + ['###'] + ['...'] * 5
    if ch == '+':
        return ['...', '...', '.#.', '###', '.#.', '...', '...', '...', '...']
    if ch == 'í':
        return ['.#', '#.', '#.', '#.', '#.', '#.', '#.', '..', '..']
    if ch == 'ç':
        g = _rows(_L['c'])
        g[7], g[8] = '..#.', '.##.'
        return g
    if ch in COMPOSE:
        base, acc = COMPOSE[ch]
        g = _rows(_L[base])
        g[0], g[1] = ACCENTS[acc]
        return g
    if ch in _L:
        return _rows(_L[ch])
    up = ch.upper()
    base = {'Á': 'A', 'É': 'E', 'Ó': 'O', 'Ú': 'U', 'Ç': 'C', 'Ã': 'A'}.get(up, up)
    if base in _U:
        return _rows(_U[base])
    return ['..'] * 9


def width(s):
    return sum(len(glyph(c)[0]) + 1 for c in s) - 1


def draw(L, s, x, y, col):
    cx = x
    for ch in s:
        g = glyph(ch)
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == '#':
                    L.rect(cx + c, y + r, 1, 1, col)
        cx += len(g[0]) + 1


def plaque(L, s, cx, y, bg=H('2e2a33'), fg=H('f6eedc')):
    """dark name plaque, light text, 2px padding + 1px dark outline (centred on cx)."""
    w = width(s) + 4
    has_desc = any(ch in 'gjpqyç,' for ch in s)
    h = 7 + 4 + (2 if has_desc else 0)
    x0 = int(cx - w / 2)
    L.begin(); L.rect(x0, y, w, h, bg); L.end(col=H('15121a'))
    draw(L, s, x0 + 2, y + 2, fg)
